#!/usr/bin/env node
/**
 * Bakes the official logo (public/brand/ciccios-logo.png) into src/art/maze/logoBits.ts: the label
 * printed on the big centre tray of the CICCIO-MAN board, at 2 px per world pixel, face on the left
 * and the outlined wordmark on the right. The logo is white on transparent with black features, so
 * every cell is one hex digit: 0-7 = white level over the bare label, 8-f = white level over black ink.
 * Deterministic: re-running rewrites an identical file.
 *
 *   node scripts/logo-bits.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'public', 'brand', 'ciccios-logo.png');
const OUT = path.join(root, 'src', 'art', 'maze', 'logoBits.ts');

/** Source boxes (px) of the face and of the wordmark, found from the logo's alpha rows. */
const FACE = { x: 8, y: 8, w: 553, h: 798 };
const WORD = { x: 26, y: 886, w: 573, h: 146 };
/** Label size and where the two parts sit on it (label px = half a world pixel). */
const LABEL = { w: 100, h: 52 };
const FACE_AT = { x: 4, y: 2, w: 33, h: 48 };
const WORD_AT = { x: 42, y: 19, w: 54, h: 14 };
const LEVELS = 8;
/** < 1 lifts the thin strokes (hairline, eyebrows, outlined letters) that area-averaging dims. */
const GAMMA = 0.7;
/** Less white than this is dropped: the logo's hairline round the hair is for black backgrounds only. */
const MIN_WHITE = 0.42;

const png = PNG.sync.read(readFileSync(SRC));

/** White and black coverage (0..1) of the source box, area-averaged with exact fractional edges. */
function cover(bx, by, bw, bh) {
  let white = 0;
  let black = 0;
  for (let y = Math.floor(by); y < Math.ceil(by + bh); y++) {
    const wy = Math.min(y + 1, by + bh) - Math.max(y, by);
    for (let x = Math.floor(bx); x < Math.ceil(bx + bw); x++) {
      const wx = Math.min(x + 1, bx + bw) - Math.max(x, bx);
      const i = (y * png.width + x) * 4;
      const a = (wx * wy * png.data[i + 3]) / 255;
      white += (a * png.data[i]) / 255;
      black += a - (a * png.data[i]) / 255;
    }
  }
  return { white: white / (bw * bh), black: black / (bw * bh) };
}

/** One hex digit: white level, +8 when the cell is mostly black ink rather than bare label. */
function cell(c) {
  const lit = c.white < MIN_WHITE ? 0 : Math.round(Math.pow(Math.min(1, c.white), GAMMA) * (LEVELS - 1));
  return (c.black > 1 - c.white - c.black ? 8 : 0) + lit;
}

const label = Array.from({ length: LABEL.h }, () => Array(LABEL.w).fill(0));
function place(box, at) {
  for (let j = 0; j < at.h; j++) {
    for (let i = 0; i < at.w; i++) {
      const bw = box.w / at.w;
      const bh = box.h / at.h;
      label[at.y + j][at.x + i] = cell(cover(box.x + i * bw, box.y + j * bh, bw, bh));
    }
  }
}
place(FACE, FACE_AT);
place(WORD, WORD_AT);

const rows = label.map((r) => `  '${r.map((v) => v.toString(16)).join('')}',`);
writeFileSync(
  OUT,
  `/** Generated by scripts/logo-bits.mjs from public/brand/ciccios-logo.png: do not edit. */
export const LOGO_LEVELS = ${LEVELS};
/** ${LABEL.w}x${LABEL.h} label px, one hex digit each: 0-7 white level on the label, 8-f on black ink. */
export const LOGO_BITS: readonly string[] = [
${rows.join('\n')}
];
`,
);
console.log(`wrote ${path.relative(root, OUT)} (${LABEL.w}x${LABEL.h}, ${LEVELS} levels)`);
