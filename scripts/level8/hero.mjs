#!/usr/bin/env node
/**
 * Rebuilds the level 8 hero art from the owner's drawing ref/level8_ciccio_hero.png:
 *   public/level8/hero/ciccio.webp      the cut-out parts of Ciccio (head, torso, arms, glove, legs) in one atlas
 *   src/game/cartoon/hero/parts.ts      where each part sits in the atlas and in the 64x64 frame, plus the joints
 * The cut itself runs in Chromium (canvas + WebP encoder), see hero-cut.mjs. Safe to re-run.
 *
 *   node scripts/level8/hero.mjs [--check <dir>]   (--check also writes the rest silhouette 256x256 and the part labels)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { CUT, cutHero } from './hero-cut.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const REF = path.join(root, 'ref', 'level8_ciccio_hero.png');
const OUT = path.join(root, 'public', 'level8', 'hero', 'ciccio.webp');
const TS = path.join(root, 'src', 'game', 'cartoon', 'hero', 'parts.ts');
const checkDir = process.argv.includes('--check') ? process.argv[process.argv.indexOf('--check') + 1] : null;

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const dataUrl = `data:image/png;base64,${readFileSync(REF).toString('base64')}`;
  const r = await page.evaluate(cutHero, { cfg: CUT, dataUrl });
  const bytes = Buffer.from(r.webp.split(',')[1], 'base64');
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, bytes);
  if (checkDir) {
    writeFileSync(path.join(checkDir, 'rest-silhouette.png'), Buffer.from(r.silUrl.split(',')[1], 'base64'));
    writeFileSync(path.join(checkDir, 'labels.png'), Buffer.from(r.labUrl.split(',')[1], 'base64'));
  }
  const n = (v) => Math.round(v * 1000) / 1000;
  const part = (p) => `  ${p.name}: { sx: ${p.sx}, sy: ${p.sy}, sw: ${p.sw}, sh: ${p.sh}, x: ${n(p.x)}, y: ${n(p.y)}, w: ${n(p.w)}, h: ${n(p.h)} },`;
  const joint = ([k, [x, y]]) => `  ${k}: { x: ${n(x)}, y: ${n(y)} },`;
  writeFileSync(
    TS,
    `/**
 * GENERATED by scripts/level8/hero.mjs from ref/level8_ciccio_hero.png — do not edit, re-run the script.
 * The cut-out parts of Ciccio in public/level8/hero/ciccio.webp: atlas rect (sx, sy, sw, sh in atlas px) and
 * the rest pose rect (x, y, w, h in HERO_FRAME units, feet at HERO_FRAME.footY); joints in frame units.
 */
export const HERO_ATLAS = { url: 'level8/hero/ciccio.webp', w: ${r.size[0]}, h: ${r.size[1]} } as const;

export interface PartRect {
  readonly sx: number;
  readonly sy: number;
  readonly sw: number;
  readonly sh: number;
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}

export const PARTS = {
${r.parts.map(part).join('\n')}
} as const satisfies Record<string, PartRect>;

export const JOINTS = {
${Object.entries(r.joints).map(joint).join('\n')}
} as const;
`,
  );
  console.log(`hero: ${OUT} ${r.size.join('x')} ${(bytes.length / 1024).toFixed(1)} KB, navy ${r.navy}, ${r.parts.length} parts, scale ${r.scale.toFixed(4)}`);
} finally {
  await browser.close();
}
