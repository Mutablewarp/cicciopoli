#!/usr/bin/env node
/**
 * Rebuilds the DOUBLE TRIPLE boss art from the owner's shirt (ref/level8_shirt_double_triple_v2.png, in colour on
 * a black shirt): the walking double burger is cut out of the shirt, quantised to its own flat palette, and split
 * into rig parts: body (bun, salsa, patties, cheddar, bacon, face), the left glove arm, the peace-sign arm and
 * the two legs in their blue sneakers, each with its share of the white sticker edge.
 *
 *   node scripts/level8/doubletriple.mjs [--debug <dir>]
 *
 * Writes public/level8/doubletriple/{body,arm-l,arm-r,leg-l,leg-r}.webp and src/game/cartoon/bosses/doubletriple/
 * sprites.ts (the source-pixel box of every part, read by the rig).
 */
import path from 'node:path';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dataUrl, openKit, save } from './oldschool-kit.mjs';
import { buildSticker } from './doubletriple-sticker.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const debugDir = args.includes('--debug') ? args[args.indexOf('--debug') + 1] : null;

const INK = '#16120f';
const CFG = {
  s: 4,
  crop: { x: 335, y: 935, w: 380, h: 375 },
  shirtLum: 70,
  keepFrac: 0.02,
  kmeansRounds: 6,
  despeckle: 2,
  stickerW: 5,
  rimW: 1.2,
  sticker: '#fbfaf6',
  rim: INK,
  outScale: 0.5,
  /** the flat palette: k-means refines the seeds, except the fixed ones (ink, white, the pinks, the tongue) */
  palette: [INK, '#f3f2ee', '#f08515', '#c96c1a', '#c64a27', '#6e2a14', '#f6d35b', '#d9646b', '#f2ab9e', '#e68fa6', '#c4161f', '#2f8496', '#1f4f5a'],
  fixed: [0, 1, 7, 8, 9, 10],
  parts: {
    armL: [[340, 1060], [400, 1062], [398, 1090], [386, 1104], [395, 1118], [410, 1135], [412, 1190], [340, 1195]],
    armR: [[606, 1090], [612, 1072], [628, 1068], [632, 1040], [640, 995], [712, 990], [712, 1100], [640, 1100], [615, 1100]],
    legL: [[405, 1190], [470, 1191], [510, 1189], [510, 1305], [400, 1305]],
    legR: [[510, 1189], [560, 1189], [645, 1186], [645, 1305], [510, 1305]],
  },
  /** the hoses a limb hides under the body (seen when it swings) */
  paint: {
    armL: [{ color: INK, poly: [[408, 1072], [420, 1070], [424, 1090], [410, 1094]] }],
    armR: [{ color: INK, poly: [[598, 1076], [614, 1072], [618, 1096], [600, 1098]] }],
    legL: [{ color: INK, poly: [[477, 1194], [503, 1194], [503, 1162], [477, 1162]] }],
    legR: [{ color: INK, poly: [[517, 1198], [553, 1198], [553, 1162], [517, 1162]] }],
  },
};

const FILES = { body: 'body', armL: 'arm-l', armR: 'arm-r', legL: 'leg-l', legR: 'leg-r' };

const { page, close } = await openKit();
try {
  const res = await page.evaluate(buildSticker, { cfg: CFG, url: dataUrl(path.join(ROOT, 'ref/level8_shirt_double_triple_v2.png')), debug: !!debugDir });
  console.log('palette', res.palette.join(' '));
  for (const [part, file] of Object.entries(FILES)) save(path.join(ROOT, 'public/level8/doubletriple', `${file}.webp`), res.files[part]);
  if (debugDir) {
    save(path.join(debugDir, 'dt_parts.png'), res.parts);
    save(path.join(debugDir, 'doubletriple_refmask.png'), res.refmask);
  }
  const round = (v) => Math.round(v * 100) / 100;
  const lines = Object.entries(res.boxes).map(([k, b]) => `  ${k}: { x: ${round(b.x)}, y: ${round(b.y)}, w: ${round(b.w)}, h: ${round(b.h)} },`);
  writeFileSync(
    path.join(ROOT, 'src/game/cartoon/bosses/doubletriple/sprites.ts'),
    `/** GENERATED by scripts/level8/doubletriple.mjs: where each part image sits on the shirt, in source px. */\nexport const DT_SRC = {\n${lines.join('\n')}\n} as const;\n`,
  );
  console.log(JSON.stringify(res.boxes));
} finally {
  await close();
}
