#!/usr/bin/env node
/**
 * Rebuilds PANCETTA LO SKATER's bitmaps from the owner's shirt (ref/level8_shirt_pancetta.png, red line
 * art): crop the pig, upscale x4, split the print into ink / paper / solid fills, despeckle, colour every
 * closed region with natural colours inside the printed lines, cut the puppet parts (head + 6 faces, the
 * waving arm, body, skateboard, the flying bacon strip) and paint what a turning part uncovers. Writes
 * public/level8/pancetta/*.webp and src/game/cartoon/bosses/pancetta/sheet.ts (frame sizes and pivots).
 *
 *   node scripts/level8/pancetta.mjs [debugDir]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCut, tsLiteral } from './brie-cut.mjs';
import { pancettaJob } from './pancetta-job.mjs';
import { pancettaPaint } from './pancetta-paint.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const debug = process.argv[2];

const data = await runCut({
  refs: { shirt: path.join(root, 'ref/level8_shirt_pancetta.png') },
  out: path.join(root, 'public/level8/pancetta'),
  debug,
  job: pancettaJob,
  libs: [pancettaPaint],
});
if (data.orphans.length) process.stdout.write(`orphan regions (shirt px): ${JSON.stringify(data.orphans)}\n`);

const ts = `/**
 * GENERATED by scripts/level8/pancetta.mjs from ref/level8_shirt_pancetta.png — do not edit by hand.
 * Pancetta's bitmap sheets (public/level8/pancetta/): frame size and the texture-pixel position of each
 * frame's top-left corner in the crop (the rig divides by PANCETTA_ART.pxPerUnit).
 */
export const PANCETTA_ART = ${tsLiteral(data.sheet)} as const;
`;
fs.writeFileSync(path.join(root, 'src/game/cartoon/bosses/pancetta/sheet.ts'), ts);
process.stdout.write('wrote src/game/cartoon/bosses/pancetta/sheet.ts\n');
