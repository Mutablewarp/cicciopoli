#!/usr/bin/env node
/**
 * Rebuilds MONSIEUR BRIE's bitmaps from the owner's shirt (ref/level8_shirt_brie_v2.png): crop the mascot,
 * upscale x4, quantise to the print's flat palette (ink, white, cheese, blue), despeckle, split it into
 * the animation parts (wedge + face expressions, beret, glove, feet, bike, wheels) and paint what a moving
 * part uncovers. Writes public/level8/brie/*.webp and src/game/cartoon/bosses/brie/sheet.ts (frame
 * sizes and anchors, crop px).
 *
 *   node scripts/level8/brie.mjs [debugDir]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCut, tsLiteral } from './brie-cut.mjs';
import { brieJob } from './brie-job.mjs';
import { briePaint } from './brie-paint.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const debug = process.argv[2];

const data = await runCut({
  refs: { shirt: path.join(root, 'ref/level8_shirt_brie_v2.png') },
  out: path.join(root, 'public/level8/brie'),
  debug,
  job: brieJob,
  libs: [briePaint],
});
if (data.orphans.length) process.stdout.write(`orphan regions (crop px): ${JSON.stringify(data.orphans)}\n`);

const ts = `/**
 * GENERATED by scripts/level8/brie.mjs from ref/level8_shirt_brie_v2.png — do not edit by hand.
 * Monsieur Brie's bitmap sheets (public/level8/brie/): frame size and the crop-pixel position of each
 * frame's top-left corner (1 crop px = 1 texture px; the rig divides by BRIE_ART.pxPerUnit).
 */
export const BRIE_ART = ${tsLiteral(data.sheet)} as const;
`;
fs.writeFileSync(path.join(root, 'src/game/cartoon/bosses/brie/sheet.ts'), ts);
process.stdout.write('wrote src/game/cartoon/bosses/brie/sheet.ts\n');
